namespace SoundMeeter.Audio;

/// <summary>
/// Источник сэмплов входного стрипа: владеет кольцевым буфером, из которого
/// шины читают своими курсорами.
///
/// Две реализации, и различие между ними ровно в том, кто наполняет кольцо:
/// <list type="bullet">
/// <item><see cref="InputSource"/> — устройство WASAPI; темп задаёт драйвер,
/// пакеты приходят в его потоке захвата;</item>
/// <item><see cref="SyntheticInputSource"/> — код приложения (синтез речи);
/// темп задаёт собственный поток источника.</item>
/// </list>
///
/// Общий контракт — <see cref="PushAudio"/>: подмешать готовые сэмплы в кольцо
/// источника. Для <see cref="InputSource"/> это внешний сигнал, подмешанный к
/// звуку устройства (так в стрип попадает модуль синтеза речи); для
/// <see cref="SyntheticInputSource"/> это единственный источник данных.
/// </summary>
public interface ISampleSource : IDisposable
{
    /// <summary>Курсор шины, читающий из кольца источника.</summary>
    RingCursor OpenCursor();

    /// <summary>
    /// Подмешивает сэмплы в кольцо источника (48 кГц, стерео, чередующиеся L/R).
    ///
    /// Вызывается из любого потока. Данные кладутся в очередь источника и уходят в
    /// кольцо в темпе воспроизведения, поэтому вызывающий не обязан сам соблюдать
    /// реальное время — и не должен: синтезатор отдаёт фразу целиком за доли
    /// секунды, и прямая запись в кольцо переполнила бы его мгновенно.
    /// </summary>
    void PushAudio(ReadOnlySpan<float> samples);

    /// <summary>
    /// Очередь внешнего звука стрипа — её забирает <see cref="BusTap"/>.
    ///
    /// Отдельная сущность, а не часть кольца: у стрипа с устройством полосы кольца
    /// уже не осталось, её занимает захват. Поэтому и держать, и забирать её
    /// приходится отдельно от кольца.
    /// </summary>
    SampleQueue External { get; }

    /// <summary>
    /// Сколько секунд подмешанного звука ещё не прозвучало.
    ///
    /// По этому числу модуль решает, что фраза дозвучала: ждать возврата из
    /// синтеза бесполезно, он ничего не говорит о том, что слышно.
    /// </summary>
    double BufferedSeconds { get; }

    /// <summary>Выбросить то, что ещё не уехало в кольцо. Уже прозвучавшее не трогаем.</summary>
    bool ClearPending();
}
