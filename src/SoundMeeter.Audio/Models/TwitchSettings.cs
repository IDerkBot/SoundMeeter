namespace SoundMeeter.Models;

/// <summary>
/// Настройки интеграции с Twitch (SM-F01).
///
/// Отдельный блок, а не часть <see cref="TextToSpeechSettings"/>, потому что чат
/// Twitch — источник данных сам по себе: его читает и модуль синтеза речи, и
/// индикатор статуса трансляции в главном окне. Смешали бы в одном классе — и
/// выключатель TTS гасил бы индикатор, а смена канала требовала бы включать
/// озвучку.
///
/// ТОКЕНА ЗДЕСЬ НЕТ, и это не упущение. <see cref="TextToSpeechSettings"/> и этот
/// класс уезжают в settings.json, который пользователь переносит между
/// компьютерами, показывает в мастере настроек и кладёт в резервную копию. Токен
/// Twitch даёт доступ к аккаунту, поэтому он лежит отдельно и зашифрован
/// средствами Windows (см. хранилище токенов в Core).
/// </summary>
public class TwitchSettings
{
    /// <summary>
    /// Подключаться к чату. По умолчанию выключено: модуль обращается к чужому
    /// сервису и читает личные сообщения, а включать это без явного решения
    /// пользователя нельзя.
    /// </summary>
    public bool Enabled { get; set; }

    /// <summary>
    /// Логин канала, который читаем, без «@» (SM-F01).
    ///
    /// Читается канал, а не тот аккаунт, под которым вошли: вошедшим аккаунтом
    /// может быть бот или модератор, а озвучивать сообщения стримера его зрителей
    /// нужно. Пусто — подключаться не к чему, модуль молчит.
    /// </summary>
    public string ChannelLogin { get; set; } = "";

    /// <summary>
    /// Показывать в главном окне, идёт ли трансляция.
    ///
    /// Отдельный выключатель, потому что проверка статуса — это запрос к API раз в
    /// минуту, и накладные расходы пользователю, который смотрит только на чат,
    /// не нужны.
    /// </summary>
    public bool ShowStreamStatus { get; set; } = true;

    /// <summary>
    /// Логин аккаунта, под которым выполнен вход. Токен при этом лежит в
    /// отдельном зашифрованном файле, а здесь только имя — чтобы в окне было видно,
    /// кем подключено, не показывая секрет.
    ///
    /// Пусто — вход не выполнен. Это поле и есть признак «подключено»: токен мог
    /// протухнуть или быть отозван, и тогда файл удаляет себя сам, а запись в
    /// настройках остаётся как напоминание, что канал был настроен.
    /// </summary>
    public string AuthorizedLogin { get; set; } = "";

    /// <summary>
    /// Идентификатор пользователя (Twitch user id) канала, к которому подключён
    /// чат. Кэш значения, полученного от API.
    ///
    /// Нужен потому, что подписка EventSub адресуется идентификатором, а не
    /// логином, и логином она не адресуется вовсе. Пусто — подключение ещё не
    /// выполнялось, канал будет опрошен при первом старте.
    /// </summary>
    public string ChannelUserId { get; set; } = "";

    /// <summary>
    /// Прятать сообщения чата, написанные авторами, у которых есть свой голос.
    /// Не путать с <c>!tts</c>: реплика без команды не озвучивается никогда, этот
    /// флаг про другое — про то, попадёт ли она в журнал и на экран.
    /// </summary>
    public bool LogAllMessages { get; set; }

    /// <summary>
    /// Границы значений. Заданы здесь по той же причине, что и
    /// <see cref="TextToSpeechSettings.Limits"/>: их трогают миграция схемы, окно
    /// настроек и разбор команд, и разъезд этих чисел означал бы, что одно
    /// обещает, а другое режет.
    /// </summary>
    public static class Limits
    {
        /// <summary>
        /// Длина логина канала. Правда Twitch — 25 символов; берём с запасом,
        /// потому что проверка приходит от сервиса, а не от нас.
        /// </summary>
        public const int LoginMaxLength = 64;

        /// <summary>Как часто опрашивать статус трансляции, миллисекунд.</summary>
        public const int StreamStatusPollMs = 30_000;
    }

    /// <summary>
    /// Логин канала в виде, пригодном для сравнения и для отправки в API:
    /// без «@», без пробелов, в нижнем регистре, обрезан по длине.
    ///
    /// Регистр именно здесь, а не в разборе команд, потому что Twitch сравнивает
    /// логины регистронезависимо, а вот наш файл мог быть отредактирован руками.
    /// </summary>
    public string NormalizedChannel()
    {
        string login = (ChannelLogin ?? "").Trim().TrimStart('@').Trim();
        if (login.Length > Limits.LoginMaxLength) login = login[..Limits.LoginMaxLength];
        return login.ToLowerInvariant();
    }

    /// <summary>Копия. Нужна там же, где копируются другие блоки настроек.</summary>
    public TwitchSettings Clone() => new()
    {
        Enabled = Enabled,
        ChannelLogin = ChannelLogin,
        ShowStreamStatus = ShowStreamStatus,
        AuthorizedLogin = AuthorizedLogin,
        ChannelUserId = ChannelUserId,
        LogAllMessages = LogAllMessages,
    };
}