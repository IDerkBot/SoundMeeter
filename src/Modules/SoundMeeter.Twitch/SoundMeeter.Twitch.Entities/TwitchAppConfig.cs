namespace SoundMeeter.Twitch.Entities;

/// <summary>
/// Сборка приложения на стороне Twitch: идентификатор клиента и признак того,
/// что модуль вообще настроен.
///
/// Константа живёт здесь, а не в <c>TwitchAuthService</c>, потому что о ней
/// должен знать и слой сценариев: <c>TwitchService</c> отвечает «настроен ли
/// модуль» ещё до всякой сети. Если бы факт остался в реализации, оркестрация
/// пришла бы за ним в <c>Contract.Implementation</c> — то есть вверх по слоям,
/// а реализация обязана знать вниз, и круг замыкался бы.
///
/// Вынесенное здесь — факт о сборке, а не о состоянии: токен, вход и подписка
/// по-прежнему живут в реализации и в контракте.
/// </summary>
public static class TwitchAppConfig
{
    /// <summary>
    /// Client ID приложения SoundMeeter.
    ///
    /// ПУСТОЙ — это не ошибка сборки, а место для вашего значения. Client ID
    /// выдаёт Twitch при регистрации приложения, и он публичен по своей сути:
    /// его нельзя спрятать в приложении, которое пользователь запускает на своём
    /// компьютере. Ровно поэтому он лежит здесь, одной строкой, а не в настройках.
    ///
    /// Как получить: twitch.tv/console → Applications → Register an Application →
    /// заполнить имя и категорию → Copy Client ID → вставить ниже и пересобрать.
    /// Для этой схемы секрет не нужен, redirect URI — тоже.
    ///
    /// Пока строка пустая, модуль честно говорит в окне «не настроено» и в сеть не
    /// ходит: так пользователь увидит причину, а не ошибку 401 от Twitch.
    /// </summary>
    public const string ClientId = "";

    /// <summary>
    /// Приложение собрано с client ID. Пока строка пустая, вход невозможен, и об
    /// этом надо сказать прямо в окне — иначе кнопка «войти» молча ничего не
    /// сделала бы.
    /// </summary>
    public static bool IsConfigured => ClientId.Length > 0;
}