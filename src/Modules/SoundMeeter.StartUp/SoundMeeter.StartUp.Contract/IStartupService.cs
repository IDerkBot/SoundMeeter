namespace SoundMeeter.Services;

/// <summary>
/// Автозапуск вместе с Windows (SM-D01).
///
/// Способ — задача планировщика <c>\SoundMeeter</c> с триггером «вход в
/// систему», <c>TASK_LOGON_INTERACTIVE_TOKEN</c> и <c>TASK_RUNLEVEL_HIGHEST</c>.
///
/// Раньше это была запись в <c>HKCU\Software\Microsoft\Windows\CurrentVersion\Run</c>,
/// и это была ошибка: приложению нужны права администратора (AppRouting меняет
/// маршрутизацию всего сеанса, а манифест объявлен как
/// <c>requireAdministrator</c>), а ветка пользователя запускается планировщиком в
/// обычном контексте. Каждый вход в Windows заканчивался запросом UAC, и если его
/// не подтверждали, микшер не стартовал вовсе. Задача, зарегистрированная из уже
/// повышенного процесса, запускает его с полным токеном администратора и без
/// запроса; дополнительные права при регистрации не нужны — приложение и так
/// работает от администратора.
///
/// Ключ <c>Run</c> вместо задачи выбирался по той причине, что не требует прав,
/// — ровно та причина и делала его негодным. Задача выживает обновление на
/// место: путь в действии абсолютный, а автообновление подставляет новые файлы в
/// каталог установки (SM-A06), поэтому путь не меняется.
/// </summary>
public interface IStartupService
{
    /// <summary>
    /// Включён ли автозапуск по состоянию системы.
    ///
    /// Чтение состояния — заодно перенос записи из ключа <c>Run</c> в задачу,
    /// если такая запись осталась от прошлых сборок: иначе автозапуск остался бы
    /// включённым, но со старым поведением (с запросом UAC), и переключатель в
    /// интерфейсе показывал бы «выключено» при фактически работающем автозапуске.
    /// Перенос не включает автозапуск заново — он сохраняет то, что пользователь
    /// уже включил, только в том механизме, который действительно работает без
    /// запроса UAC.
    /// </summary>
    bool IsEnabled { get; }

    /// <summary>
    /// Включает или выключает автозапуск. Возвращает итоговое состояние: если
    /// запись в систему не удалась, возвращается то, что получилось, а не
    /// желаемое — иначе переключатель в интерфейсе показывал бы неправду.
    /// </summary>
    bool SetEnabled(bool enabled);
}
