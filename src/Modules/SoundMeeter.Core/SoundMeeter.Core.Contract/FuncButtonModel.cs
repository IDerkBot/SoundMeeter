namespace SoundMeeter.Models;

/// <summary>
/// Назначение одной пользовательской кнопки FUNC на входном стрипе: список
/// выходов (аппаратных OUT и/или виртуальных VIRT), в которые стрип уходит
/// по нажатию кнопки, и правило применения.
///
/// Само назначение — это заготовка, а не роутинг: пока кнопку не нажали,
/// маршруты стрипа не трогаются. Иначе ошибка в настройке (сняли галку с
/// единственного выхода) молча убрала бы звук со стрипа, и «кнопка ничего не
/// делает» выглядело бы поломкой.
/// </summary>
public class FuncButtonModel
{
    /// <summary>Id выходных шин, в которые кнопка отправляет стрип.</summary>
    public List<string> BusIds { get; set; } = new();

    /// <summary>
    /// true (по умолчанию) — кнопка приводит роутинг стрипа ровно к своему
    /// списку: выбранные включаются, остальные выключаются. Это «сценарий»
    /// одним щелчком (в колонки / в стрим и обратно).
    /// false — кнопка только дописывает свои выходы к текущим, не трогая
    /// остальные: удобно, когда один выход нужен всегда, а кнопка добавляет
    /// второй.
    /// </summary>
    public bool Exclusive { get; set; } = true;

    /// <summary>Своя подпись кнопки вместо «F1»/«F2». Пусто — номер слота.</summary>
    public string Label { get; set; } = "";
}
