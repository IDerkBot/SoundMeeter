namespace SoundMeeter.Midi.Entities;

/// <summary>
/// Что именно сломалось в сценарии MIDI. Отдельный перечень, а не строка со
/// сообщением, потому что ошибку переводят на язык уже наверху — в Presentation
/// (<c>Loc.Get(result.MessageKey)</c>), а в самом модуле нужен разбор кода
/// (логирование, выбор ветки), а не готовая фраза на двух языках.
///
/// Перечень закрытый намеренно: это не «исключение приложения», а исчерпывающий
/// список исходов, которые может иметь сценарий. Новое состояние не появится
/// молча — компилятор потребует разобрать его в <see cref="MidiResult"/>.
/// </summary>
public enum MidiError
{
    /// <summary>Сценарий отработал штатно.</summary>
    None = 0,

    /// <summary>
    /// Сохранённого MIDI-устройства нет в системе. Это не ошибка в строгом
    /// смысле — контроллер могли просто отключить, — но сценарий обязан сказать
    /// об этом вызывающему, иначе UI напишет «слушаем», а MIDI закрыт.
    /// </summary>
    DeviceNotFound = 1,

    /// <summary>
    /// Устройство есть, но его не удалось открыть: занято другим приложением,
    /// нет прав, отвалился драйвер. NAudio бросает здесь исключение, которое
    /// <c>MidiService.Open</c> проглатывает, — поэтому сверяться приходится по
    /// <c>IsOpen</c> после вызова.
    /// </summary>
    DeviceOpenFailed = 2,

    /// <summary>
    /// Привязка указывает на стрип, которого больше нет: полоса удалена из
    /// микшера, а настройка приехала из файла с другой машины.
    /// </summary>
    StripMissing = 3,

    /// <summary>
    /// Стрип найден, но параметра на нём нет. Обычно это привязка кнопки
    /// эффекта к выходной шине или параметра входа к шине.
    /// </summary>
    ParameterUnsupported = 4
}