namespace SoundMeeter.Audio;

/// <summary>
/// Задержка аудиопути микшера. Значения управляют буферами устройств (endpoint)
/// WASAPI на входе и выходе, а вместе с ними — всей сквозной задержкой.
///
/// ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ КЛАСС, А НЕ ДВЕ КОНСТАНТЫ У МЕСТА ИСПОЛЬЗОВАНИЯ.
/// NAudio отдаёт наружу только <b>запрос</b> латентности. Реальную величину
/// выбирает Windows и драйвер: <c>IAudioClient.Initialize</c> получает
/// <c>hnsBufferDuration</c> как пожелание, а <c>GetBufferSize</c> возвращает то,
/// что решено. Дальше <c>WasapiPlayer</c> работает ровно с этим размером:
/// <c>bufferFrameCount = audioClient.BufferSize</c>, и буфер постоянно
/// доливается до полного. То есть <b>латентность микшера равна глубине буфера
/// устройства</b>, и единственный способ её уменьшить — запросить меньше.
///
/// ГЛАВНАЯ СИМПТОМАТИКА, КОТОРУЮ ЭТО ЧИНИТ.
/// Пока буфер не опустошается, в нём уже стоит до секунды тишины. Поэтому
/// «звук пропадает и начинается через промежуток времени» после остановки
/// воспроизведения: возобновлённый сигнал попадает в конец очереди и доходит
/// до ушей только после того, как всё, что было записано раньше, вытеснено
/// устройством. На нескольких каналах одновременно это незаметно — микс не
/// опустошается целиком, и мёртвого времени не слышно.
///
/// ПОЧЕМУ НЕ 10 МС.
/// Задержка на слух тем заметнее, чем она постоянна: она перестаёт восприниматься
/// как отдельное событие. Цена малого буфера — частота пробуждений потока
/// (событие WASAPI на каждый период) и запас на поток захвата. 20/25 мс берутся
/// с округлением до периода движка: Windows всё равно округляет запрос до целого
/// числа периодов, и значения меньше периода устройства ничего не выигрывают,
/// только добавляют джиттера. Итоговые ~40-50 мс сквозной задержки на игре и
/// микрофоне — ниже порога заметности, в отличие от прежних 200 мс и выше.
/// </summary>
public static class AudioEngineDefaults
{
    /// <summary>
    /// Буфер входного эндпоинта, мс. Запрашивается у микрофона и у loopback
    /// источников. Это «возраст» самого старого отсчёта, который ещё не прочитан,
    /// плюс джиттер пробуждения — до половины периода.
    /// </summary>
    /// <remarks>
    /// Раньше здесь стояло 100 мс, и изменить это было нечем: публичные
    /// конструкторы <c>WasapiCapture</c>/<c>WasapiLoopbackCapture</c> в NAudio
    /// жёстко вели в <c>(device, useEventSync: false, 100)</c> — то есть вдобавок
    /// ещё и опрос через <c>Thread.Sleep</c>, а не по событию. У
    /// <c>WasapiLoopbackCapture</c> другого конструктора нет вообще.
    /// </remarks>
    public const int InputBufferMilliseconds = 20;

    /// <summary>
    /// Буфер выходного эндпоинта, мс. Запрашивается у каждой шины. В сумме с
    /// <see cref="InputBufferMilliseconds"/> даёт сквозную задержку микшера.
    /// </summary>
    /// <remarks>
    /// Дополнительно для выхода запрашивается низкая латентность через
    /// IAudioClient3 (<c>WasapiPlayerBuilder.WithLowLatency</c>): если движок её
    /// даёт, берётся его минимальный период, и эти 25 мс не применяются вовсе.
    /// Запрос мягкий (<c>required: false</c>) — отказ не является ошибкой.
    /// </remarks>
    public const int OutputBufferMilliseconds = 25;

    /// <summary>
    /// Задержка, добавляемая кольцевым буфером между захватом и шинами.
    /// </summary>
    /// <remarks>
    /// Работает не «буфером задержки», а пропуском: читатель забирает столько,
    /// сколько просит шина, и при отставании больше ёмкости перешагивает через
    /// потерянное, а не копит его дальше. Поэтому на практике вклад кольца в
    /// задержку близок к нулю, а сам размер кольца — это потолок простоя
    /// (разрыв в звуке), а не добавка к задержке.
    /// </remarks>
    public const int RingBufferMilliseconds = 1000;
}