namespace SoundMeeter.TextToSpeech.Entities;

/// <summary>
/// Имена, по которым модуль синтеза речи узнаёт собственный канал.
///
/// Живут здесь, а не в <c>TtsViewModel</c>, потому что это факты о канале, а не
/// о представлении. Раньше константы стояли во ViewModel'е, и на них ссылались
/// другие слои: окно настроек брало имя канала оттуда, а ядро — псевдо-Id для
/// пункта «отдельный канал TTS». Получалось, что знание о домене жило в одном
/// месте и оттуда раздавалось вверх по слоям.
///
/// Совпадений с настоящими Id быть не может: настоящие —
/// <c>Guid.NewGuid().ToString("N")</c>, то есть 32 шестнадцатеричных символа,
/// а здесь символ «@», которого в Guid не бывает.
/// </summary>
public static class TtsStripNames
{
    /// <summary>
    /// Имя стрипа, который создаёт модуль. Одно на всё приложение: по нему
    /// движок находит уже созданный канал вместо того, чтобы плодить новые.
    /// </summary>
    public const string Generated = "TTS";

    /// <summary>
    /// Псевдо-Id для пункта «отдельный канал TTS» в списке выбора. Такой Id не
    /// может совпасть с настоящим.
    /// </summary>
    public const string GeneratedSentinel = "@tts";
}